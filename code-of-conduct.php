                                     <p>
                                         The Federation of Indian Direct Selling Industries (FIDSI) is committed to ensuring the highest standards of ethics, compliance, and professionalism in the Indian direct selling industry. Our Code of Conduct serves as a guiding framework for all member companies to operate responsibly, transparently, and in alignment with national laws and consumer interests.
                                         </p><br>
                                         <h4>Ethical Business Practices</h4>
                                         <p><strong>All FIDSI member companies shall:</strong></p>
                                         <ul>
                                             <li>Conduct business with integrity, fairness, and transparency at all levels.</li>
                                             <li>Present products and business opportunities truthfully, without misleading claims.</li>
                                             <li>Refrain from any form of coercion, misrepresentation, or deceptive marketing.</li>
                                             <li>Ensure advertisements, income representations, and testimonials are factual and verifiable.</li>
                                             <li>Avoid any activity that may be construed as a pyramid scheme or money circulation scheme, as prohibited under Indian law.</li>
                                             <li>Promote fair competition and respect the operations of other legitimate businesses.</li>
                                         </ul><br>
                                         <h4>Standards for Member Companies</h4>
                                         <p><strong>FIDSI members are required to:</strong></p>
                                            <ul>
                                                <li>Fully comply with all relevant laws and regulations, including the Consumer Protection Act, 2019, Direct Selling Rules, 2021, and E-Commerce Rules, 2020.</li>
                                                <li>Clearly communicate business terms, return policies, and earning disclosures to all direct sellers.</li>
                                                <li>Offer high-quality products and ensure transparent pricing.</li>
                                                <li>Provide training programs to educate direct sellers about products, company policies, and ethical conduct.</li>
                                                <li>Maintain a clean and updated database of active direct sellers, sales figures, and commissions.</li>
                                                <li>Honor product return, refund, and buyback policies as per applicable rules and internal policies.</li>
                                            </ul><br>
                                           <h6>Grievance Redressal Mechanism</h6>
                                            <p>To ensure transparency and consumer trust, every FIDSI member company must establish a robust and accessible grievance redressal system.</p>
                                            <ul>
                                                <li>A Grievance Redressal Officer must be appointed and their contact details published on the company website.</li>
                                                <li>Complaints should be acknowledged within 48 hours and resolved within 30 days.</li>
                                                <li>Members must maintain a formal record of all grievances and their resolutions.</li>
                                                <li>Escalated issues must be addressed cooperatively in coordination with FIDSI and relevant authorities.</li>
                                                <li>Companies should offer both online and offline grievance submission channels to ensure accessibility.</li>
                                            </ul>
