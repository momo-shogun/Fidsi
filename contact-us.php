<script>
$("#contactForm").on('submit',(function(e) {
    e.preventDefault();

    $(':input[type="submit"]').prop('disabled', true);
    $.ajax({
        url: "contact-action.php",type: "POST",data: new FormData(this),contentType: false,cache: false,processData:false,
        success: function(dataResult){
            if(dataResult != null){
                $(':input[type="submit"]').prop('disabled', false);
                if(dataResult == 200){
                    Swal.fire({title: "Success!",text: "Record Submitted!",icon: "success"});
                    $("#contactForm").trigger("reset");
                }else if(dataResult == 300){
                    Swal.fire({title: "Oppss..!",text: "Something went wrong!",icon: "error"});
                }
            }
        },
        error: function(){}
    });
}));
</script>
