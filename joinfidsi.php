                                                   <h5>Internal Policies</h5>
                                                   <ul>
                                                       <li>Every FIDSI Member entity, its Directors / Partners, employees, Franchisees, stockists and Direct Sellers are bound by the FIDSI Oath.</li>
                                                       <li>FIDSI is managed by the following bodies:</li>
                                                       <li>
                                                           <ul>
                                                               <li>A Committee consisting of its President, General Secretary, Treasurer and General Manager to oversee all activities of the Federation, admission of Members, Accounting, appointment and retre4nchment of employees, organizing Discussions, Conferences, seminars, events, meeting and representing FIDSI members before Government(s) and its affiliated/associated organizations, collection, receiving and spending of FIDSI Funds, Maintaining Bank Accounts, Deposits and transactions within the Budget passed by the Governing Board.</li>
                                                               <li>A Governing Board comprising of the President, General Secretary, Treasurer, General Manager and Patron Members (Maximum five numbers) to approve and formalize policies of FIDSI, its Annual Budget, Receipt & Expenses statement and Balance sheet.</li>
                                                               
                                                           </ul>
                                                       </li>
                                                       
                                                   </ul>
                                                   <h5>Self-Regulation</h5>
                                                   <p>
                                                       The FIDSI Oath is not law, but its obligatory and FIDSI expects that its Members shall pursue an ethical, legitimate and law-abiding Direct selling business. Non-observance of this Oath does not create any civil law responsibility or criminal liability. With cessation of its FIDSI membership, an Entity it shall no longer be bound by this Oath. It may be noted clearly that Membership of FIDSI may not be construed, in any form whatsoever, an approval of the legitimacy and legal status of the Member.
                                                        <br><br>
                                                        FIDSI expects its members to comply with all requirements of local laws as applicable to Direct selling business in the specified local, district, region, zone and state and central, as the case may be.
                                                   </p>
                                                   <h5>Local Regulation</h5>
                                                  <p>Companies and Direct Sellers must comply with all requirements of laws in India. Therefore, this Code does not restate all legal obligations. Compliance by Companies and Direct Sellers with laws of India that pertains to Direct Selling is a condition of acceptance of membership in FIDSI.</p>
                                                   <h5>Resignation</h5>
                                                   <p>Any member may withdraw from FIDSI by giving three months notice, in within, to the President, with the intention to do so provided that the annual subscription for the current year and any other dues have been fully paid up.</p>
                                                   <h5>Cessation of Membership</h5>
                                                   <p>Any member may withdraw from the membership of FIDSI by giving a written notice of its intention and the same shall be approved immediately subject to clearance of any dues whatsoever, on account of membership or event contribution (s) or otherwise. Similarly the membership of a Member can be terminated at any time, without prior notice whatsoever, by the Governing Board of FIDSI, if an entity, its Directors / Partners / CEO have been convicted by a competent court of law for violating any law of the land whatsoever or is indulging any act which may harm the name, goodwill and reputation of FIDSI and its members. The Governing Board can also suspend the membership for a specified period if a Member is accused of committing any crime or violation of law of land.</p>
